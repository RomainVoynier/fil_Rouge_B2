ALTER TABLE public.equipments
    ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW();
ALTER TABLE public.incidents
    ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW();

CREATE INDEX IF NOT EXISTS idx_incidents_equipment_id
    ON public.incidents (equipment_id);
CREATE INDEX IF NOT EXISTS idx_incidents_user_id
    ON public.incidents (user_id);
CREATE INDEX IF NOT EXISTS idx_incidents_status_created_at
    ON public.incidents (status, created_at DESC);

CREATE OR REPLACE FUNCTION public.update_timestamp_column()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_users_updated_at ON public.users;
CREATE TRIGGER trg_users_updated_at
    BEFORE UPDATE ON public.users
    FOR EACH ROW EXECUTE FUNCTION public.update_timestamp_column();

DROP TRIGGER IF EXISTS trg_equipments_updated_at ON public.equipments;
CREATE TRIGGER trg_equipments_updated_at
    BEFORE UPDATE ON public.equipments
    FOR EACH ROW EXECUTE FUNCTION public.update_timestamp_column();

DROP TRIGGER IF EXISTS trg_incidents_updated_at ON public.incidents;
CREATE TRIGGER trg_incidents_updated_at
    BEFORE UPDATE ON public.incidents
    FOR EACH ROW EXECUTE FUNCTION public.update_timestamp_column();

CREATE OR REPLACE VIEW public.v_operator_active_incidents
WITH (security_invoker = true)
AS
SELECT
    i.id AS incident_id,
    e.name AS equipment_name,
    i.status,
    i.created_at,
    i.title,
    i.severity,
    i.priority,
    i.equipment_id,
    i.user_id,
    i.updated_at
FROM public.incidents AS i
LEFT JOIN public.equipments AS e ON e.id = i.equipment_id
WHERE i.status <> 'resolved';

CREATE OR REPLACE VIEW public.v_audit_incidents_log
WITH (security_invoker = true)
AS
SELECT
    id,
    equipment_id,
    status,
    created_at,
    updated_at,
    title,
    severity,
    priority,
    user_id
FROM public.incidents;

CREATE OR REPLACE FUNCTION public.fn_incident_metrics()
RETURNS TABLE (
    total_equipments BIGINT,
    total_incidents BIGINT,
    open_incidents BIGINT
)
LANGUAGE sql
STABLE
SECURITY INVOKER
SET search_path = pg_catalog, public
AS $$
    SELECT
        (SELECT COUNT(*) FROM public.equipments),
        (SELECT COUNT(*) FROM public.incidents),
        (SELECT COUNT(*) FROM public.incidents WHERE status = 'open');
$$;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'nexus_operator') THEN
        CREATE ROLE nexus_operator NOLOGIN;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'nexus_auditor') THEN
        CREATE ROLE nexus_auditor NOLOGIN;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'nexus_operator_user') THEN
        CREATE ROLE nexus_operator_user LOGIN INHERIT;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'nexus_auditor_user') THEN
        CREATE ROLE nexus_auditor_user LOGIN INHERIT;
    END IF;
END;
$$;

ALTER ROLE nexus_operator NOLOGIN;
ALTER ROLE nexus_auditor NOLOGIN;
ALTER ROLE nexus_operator_user LOGIN INHERIT;
ALTER ROLE nexus_auditor_user LOGIN INHERIT;
GRANT nexus_operator TO nexus_operator_user;
GRANT nexus_auditor TO nexus_auditor_user;
GRANT USAGE ON SCHEMA public TO nexus_operator, nexus_auditor;

REVOKE ALL ON TABLE public.users, public.equipments, public.incidents
    FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE public.v_operator_active_incidents, public.v_audit_incidents_log
    FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.fn_incident_metrics()
    FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE public.users FROM nexus_operator, nexus_auditor;
REVOKE ALL ON TABLE public.equipments, public.incidents
    FROM nexus_operator, nexus_auditor;
REVOKE ALL ON SEQUENCE
    public.equipments_id_seq, public.incidents_id_seq
    FROM PUBLIC, anon, authenticated, nexus_operator, nexus_auditor;

GRANT SELECT, INSERT, UPDATE
    ON TABLE public.equipments, public.incidents TO nexus_operator;
REVOKE DELETE ON TABLE public.equipments, public.incidents FROM nexus_operator;
GRANT USAGE, SELECT ON SEQUENCE
    public.equipments_id_seq, public.incidents_id_seq TO nexus_operator;
GRANT SELECT ON public.v_operator_active_incidents TO nexus_operator;
GRANT EXECUTE ON FUNCTION public.fn_incident_metrics() TO nexus_operator;

GRANT SELECT ON TABLE public.equipments, public.incidents TO nexus_auditor;
GRANT SELECT ON public.v_audit_incidents_log TO nexus_auditor;
GRANT EXECUTE ON FUNCTION public.fn_incident_metrics() TO nexus_auditor;

